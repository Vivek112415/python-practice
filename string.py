                                    # Creating a list

fruits = ["Apple", "Banana", "Mango", "Orange", "Grapes"]

print("Original List:", fruits)

# Accessing
print("Accessing:", fruits[0])
 
# Slicing
print("Slicing:", fruits[1:4])

# Modifying
fruits[2] = "Pineapple"
print("Modifying:", fruits)

# Adding
fruits.append("Watermelon")
print("Adding:", fruits)

# Removing
fruits.remove("Banana")
print("Removing:", fruits)

# Sorting
fruits.sort()
print("Sorting:", fruits)

# Reversing
fruits.reverse()
print("Reversing:", fruits)

# Finding Length
print("Length:", len(fruits))


